ll gcd(ll a, ll b) {
    return b == 0 ? a : gcd(b, a % b);
}
ll lcm(ll a, ll b) {
    return a * (b / gcd(a, b));
}
ll modpow(ll a, ll e, ll mod = MOD) {
    ll r = 1;
    while (e) {
        if (e & 1) r = (r * a) % mod;
        a = (a * a) % mod;
        e >>= 1;
    }
    return r;
}

void solve() {
	int n;
        cin >> n;
        vector<vector<pair<int,int>>> children(n + 1);
        vector<int> parents(n - 1), types(n - 1);
        for (int i = 0; i < n - 1; i++) cin >> parents[i];
        for (int i = 0; i < n - 1; i++) cin >> types[i];
        for (int i = 0; i < n - 1; i++) {
            int p = parents[i];
            int t = types[i];
            children[p].push_back({i + 2, t});
        }
        int node = 1;
        while (!children[node].empty()) {
            int chosen = -1;
            for (auto [child, type] : children[node]) {
                if (type != 1) {
                    chosen = child;
                    break;
                }
            }
            if (chosen == -1) chosen = children[node][0].first;
            node = chosen;
        }
        
        cout << node << "\n";
}

